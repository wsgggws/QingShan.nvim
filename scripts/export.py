#!/usr/bin/env python3
"""Export native themes and README swatches from the Neovim palette. No Python dependencies."""

import argparse
import json
import plistlib
import subprocess
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Persistent identity: preserve the original seed across repository renames.
ALFRED_ID = "theme.custom." + str(uuid.uuid5(uuid.NAMESPACE_URL, "qingshan.nvim/alfred/QingShan")).upper()


def palette():
    result = subprocess.run(
        ["nvim", "--headless", "-u", "NONE", "-l", str(ROOT / "scripts/palette_json.lua")],
        check=True,
        capture_output=True,
        text=True,
    )
    data = json.loads(result.stdout)
    # Lua hash iteration is intentionally unordered; make exports reproducible.
    return {"colors": dict(sorted(data["colors"].items())), "terminal": data["terminal"]}


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def wezterm(p, ansi):
    values = {
        "foreground": p["fg"],
        "background": p["bg"],
        "cursor_bg": p["jade"],
        "cursor_border": p["jade"],
        "cursor_fg": p["bg_dark"],
        "selection_bg": p["jade"],
        "selection_fg": p["bg_dark"],
        "compose_cursor": p["gold"],
        "split": p["border"],
        "scrollbar_thumb": p["border"],
    }
    text = (
        '# Generated by scripts/export.py; edit lua/qingshan/palette.lua.\n[metadata]\nname = "QingShan"\n\n[colors]\n'
    )
    text += "".join(f'{key} = "{value}"\n' for key, value in values.items())
    text += f"ansi = {json.dumps(ansi[:8])}\nbrights = {json.dumps(ansi[8:])}\n"
    text += f'\n[colors.tab_bar]\nbackground = "{p["bg_dark"]}"\n'
    for name, fg, bg in [
        ("active_tab", p["jade"], p["bg_highlight"]),
        ("inactive_tab", p["fg_dim"], p["bg_dark"]),
        ("inactive_tab_hover", p["fg"], p["bg_float"]),
        ("new_tab", p["comment"], p["bg_dark"]),
        ("new_tab_hover", p["jade"], p["bg_float"]),
    ]:
        text += f'\n[colors.tab_bar.{name}]\nfg_color = "{fg}"\nbg_color = "{bg}"\n'
    return text


