def swatches(p):
    """Generate README color samples from the same palette as the themes."""
    roles = ("bg", "fg", "comment", "keyword", "jade", "sand", "string", "gold")
    return {
        f"assets/swatches/{role}.svg": (
            '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="18" '
            f'viewBox="0 0 48 18" role="img" aria-label="{p[role]}">\n'
            f"  <title>{p[role]}</title>\n"
            f'  <rect width="48" height="18" rx="3" fill="{p[role]}"/>\n'
            "</svg>\n"
        )
        for role in roles
    }


def artifacts(data):
    p, ansi = data["colors"], data["terminal"]
    return {
        **swatches(p),
        "extras/palette.json": json_text(data),
        "extras/wezterm/QingShan.toml": wezterm(p, ansi),
        "extras/tmux/qingshan.conf": tmux(p),
        "extras/tmux/qingshan.oh-my-tmux.conf": oh_my_tmux(p),
        "extras/fzf/qingshan.sh": fzf(p),
        "extras/bat/QingShan.tmTheme": bat(p),
        "extras/delta/qingshan.gitconfig": delta(p),
        "extras/alfred/QingShan Dark Large.alfredappearance": json_text(alfred(p)),
        "extras/alfred/qingshan.plist": plistlib.dumps(
            {"lightthemeuid": ALFRED_ID, "darkthemeuid": ALFRED_ID}
        ).decode(),
        "extras/slides/qingshan_theme.json": json_text(slides(p)),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed exports differ from the palette")
    args = parser.parse_args()
    stale = []
    for name, content in artifacts(palette()).items():
        target = ROOT / name
        if target.exists() and target.read_text() == content:
            continue
        if args.check:
            stale.append(name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
            print(name)
    if stale:
        raise SystemExit("Outdated exports; run python3 scripts/export.py:\n" + "\n".join(stale))


if __name__ == "__main__":
    main()
