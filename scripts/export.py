def bat(p):
    settings = [
        {
            "settings": {
                "background": p["bg"],
                "foreground": p["fg"],
                "caret": p["jade"],
                "selection": p["bg_visual"],
                "lineHighlight": p["bg_highlight"],
                "invisibles": p["border"],
                "gutter": p["bg"],
                "gutterForeground": p["comment"],
            }
        }
    ]
    scopes = [
        ("comment", "comment", "italic"),
        ("keyword, storage", "keyword", "bold"),
        ("keyword.operator, punctuation", "fg_dim", ""),
        ("string", "string", ""),
        ("constant, constant.numeric", "gold", ""),
        ("constant.language", "gold", "bold"),
        ("constant.character.escape", "sand", ""),
        ("variable", "fg", ""),
        ("variable.parameter", "sand", ""),
        ("variable.language, support.variable", "sand", ""),
        ("entity.name.function, support.function", "jade", ""),
        ("entity.name.type, entity.name.class, support.type, support.class", "bamboo", ""),
        ("entity.name.tag", "bamboo", ""),
        ("entity.other.attribute-name", "jade", ""),
        ("meta.preprocessor, entity.name.function.preprocessor", "sand", ""),
        ("invalid, invalid.illegal", "red", "underline"),
        ("invalid.deprecated", "comment", "strikethrough"),
        ("markup.heading", "jade", "bold"),
        ("markup.bold", "fg", "bold"),
        ("markup.italic", "fg", "italic"),
        ("markup.underline.link", "jade", "underline"),
        ("markup.raw, markup.inline.raw", "string", ""),
        ("markup.inserted", "bamboo", ""),
        ("markup.deleted", "red", ""),
        ("markup.changed", "gold", ""),
    ]
    for scope, role, style in scopes:
        value = {"foreground": p[role]}
        if style:
            value["fontStyle"] = style
        settings.append({"scope": scope, "settings": value})
    return plistlib.dumps(
        {"name": "QingShan", "semanticClass": "theme.dark.qingshan", "settings": settings}, sort_keys=False
    ).decode()


